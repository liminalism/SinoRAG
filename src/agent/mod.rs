//! `sinorag agent` — launch opencode with the SinoRAG MCP server pre-wired.
//!
//! The agent subcommand is a thin launcher:
//!   1. Resolve the runtime workdir.
//!   2. Resolve the opencode binary (flag → env → PATH).
//!   3. Refresh `<workdir>/.opencode/opencode.json` pointing opencode at
//!      `<this exe> mcp ...` (path resolved via `std::env::current_exe`).
//!   4. Refresh `<workdir>/AGENTS.md` from embedded doctrine.
//!   5. Exec opencode with that working directory.
//!
//! Single binary, no separate server process for the user to manage.

pub mod doctrine;

use std::path::PathBuf;
use std::process::Command;

use anyhow::{anyhow, Context, Result};
use serde_json::json;

pub struct AgentArgs {
    pub opencode: Option<PathBuf>,
    pub pack: Option<PathBuf>,
    pub allow_admin_tools: bool,
    pub writable: bool,
    pub output_root: Option<PathBuf>,
    pub dry_run: bool,
}

const AGENTS_MD_MANAGED_BODY: &str = include_str!("doctrine/agents_md.md");
const SENTINEL_BEGIN: &str =
    "<!-- BEGIN sinorag-managed: doctrine block (regenerated by `sinorag agent`) -->";
const SENTINEL_END: &str = "<!-- END sinorag-managed -->";

pub fn run(args: AgentArgs) -> Result<()> {
    let outcome = launch(args);
    if let Err(err) = &outcome {
        hold_console_open(err);
    }
    outcome
}

/// `sinorag agent` is what a Start Menu or desktop shortcut runs. Started
/// that way it owns its console window, which closes the moment the process
/// exits: a failure (OpenCode not installed, say) would flash by unread. So
/// when nothing else shares the console, say what happened and wait.
fn hold_console_open(err: &anyhow::Error) {
    if !console_is_ours_alone() {
        return;
    }
    eprintln!();
    if err.downcast_ref::<OpencodeExited>().is_some() {
        // It ran; whatever it printed on the way out is still on screen.
        eprintln!("{err}.");
    } else {
        eprintln!("SinoRAG could not start the chat session:");
        eprintln!("  {err:#}");
        eprintln!();
        eprintln!("This shortcut opens OpenCode (https://opencode.ai), the program you talk to.");
        eprintln!("If it is not installed, install it and open this shortcut again.");
    }
    if let Ok(exe) = std::env::current_exe() {
        eprintln!();
        eprintln!("Any other MCP client can use the documents as well. Give it this command:");
        eprintln!("  \"{}\" mcp", strip_extended_prefix(exe).display());
    }
    eprintln!();
    eprint!("Press Enter to close this window. ");
    let _ = std::io::Write::flush(&mut std::io::stderr());
    let _ = std::io::stdin().read_line(&mut String::new());
}

/// OpenCode started and then ended in failure: not a problem with finding
/// or launching it.
#[derive(Debug)]
struct OpencodeExited(std::process::ExitStatus);

impl std::fmt::Display for OpencodeExited {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "opencode exited with status {}", self.0)
    }
}

impl std::error::Error for OpencodeExited {}

#[cfg(windows)]
fn console_is_ours_alone() -> bool {
    #[link(name = "kernel32")]
    extern "system" {
        fn GetConsoleProcessList(process_list: *mut u32, process_count: u32) -> u32;
    }
    let mut attached = [0u32; 2];
    // SAFETY: the buffer holds the two ids the count allows.
    unsafe { GetConsoleProcessList(attached.as_mut_ptr(), attached.len() as u32) == 1 }
}

#[cfg(not(windows))]
fn console_is_ours_alone() -> bool {
    false
}

fn launch(args: AgentArgs) -> Result<()> {
    // `main.rs` already chdir's into the exe's directory at startup so the
    // binary works the same regardless of where it was invoked. That's where
    // the bundled `data/` pack lives, so it's also the right workdir for
    // opencode — no flag needed.
    let workdir = resolve_workdir()?;
    let self_exe = std::env::current_exe()
        .context("failed to resolve current_exe for MCP launcher")?
        .canonicalize()
        .context("failed to canonicalize current_exe")?;
    let self_exe = strip_extended_prefix(self_exe);

    write_opencode_config(
        &workdir,
        &self_exe,
        args.pack.as_deref(),
        args.allow_admin_tools,
        args.writable,
        args.output_root.as_deref(),
    )?;
    write_agents_md(&workdir)?;

    if args.dry_run {
        eprintln!(
            "agent: dry-run wrote {}/.opencode/opencode.json and AGENTS.md",
            workdir.display()
        );
        return Ok(());
    }

    let opencode = resolve_opencode(args.opencode)?;
    eprintln!(
        "agent: launching {} in {}",
        opencode.display(),
        workdir.display()
    );

    let status = Command::new(&opencode)
        .current_dir(&workdir)
        .status()
        .with_context(|| format!("failed to spawn opencode at {}", opencode.display()))?;
    if !status.success() {
        return Err(OpencodeExited(status).into());
    }
    Ok(())
}

fn resolve_workdir() -> Result<PathBuf> {
    let dir = std::env::current_dir().context("failed to read current directory")?;
    let abs = dir
        .canonicalize()
        .with_context(|| format!("failed to canonicalize workdir {}", dir.display()))?;
    Ok(strip_extended_prefix(abs))
}

/// On Windows, `canonicalize` returns extended-length paths prefixed with
/// `\\?\`. Many cross-platform tools (opencode included) choke on that form;
/// strip it back to a plain path when it's safe to do so.
fn strip_extended_prefix(p: PathBuf) -> PathBuf {
    #[cfg(windows)]
    {
        let s = p.to_string_lossy();
        if let Some(rest) = s.strip_prefix(r"\\?\") {
            // Don't strip the prefix off a UNC path (`\\?\UNC\server\share`):
            // dropping it would yield a malformed path.
            if !rest.starts_with("UNC\\") {
                return PathBuf::from(rest);
            }
        }
    }
    p
}

fn resolve_opencode(flag: Option<PathBuf>) -> Result<PathBuf> {
    crate::which::resolve_binary(flag.as_deref(), "OPENCODE_BIN", "opencode").ok_or_else(|| {
        anyhow!(
            "could not locate opencode binary. Pass --opencode <path>, \
                 set $OPENCODE_BIN, or install opencode on PATH. \
                 Run `sinorag setup opencode` for diagnostics."
        )
    })
}

fn write_opencode_config(
    workdir: &std::path::Path,
    self_exe: &std::path::Path,
    pack: Option<&std::path::Path>,
    allow_admin_tools: bool,
    writable: bool,
    output_root: Option<&std::path::Path>,
) -> Result<()> {
    let dir = workdir.join(".opencode");
    std::fs::create_dir_all(&dir).with_context(|| format!("failed to create {}", dir.display()))?;

    let mut command = vec![self_exe.to_string_lossy().into_owned(), "mcp".to_string()];
    if let Some(p) = pack {
        command.push("--pack".to_string());
        command.push(p.to_string_lossy().into_owned());
    }
    if allow_admin_tools {
        command.push("--allow-admin-tools".to_string());
    }
    if writable {
        command.push("--writable".to_string());
    }
    if let Some(root) = output_root {
        command.push("--output-root".to_string());
        command.push(root.to_string_lossy().into_owned());
    }

    let config = json!({
        "$schema": "https://opencode.ai/config.json",
        "mcp": {
            "sinorag": {
                "type": "local",
                "command": command,
                "enabled": true
            }
        }
    });

    let path = dir.join("opencode.json");
    // The file is OpenCode's project configuration, and the user may have
    // put a model or provider in it. Only the `sinorag` MCP entry is ours:
    // set that and keep the rest.
    let existing = std::fs::read_to_string(&path).ok();
    let merged = merge_opencode_config(existing.as_deref(), config);
    let text = serde_json::to_string_pretty(&merged)?;
    if existing.as_deref() == Some(text.as_str()) {
        return Ok(());
    }
    if let Some(previous) = &existing {
        if serde_json::from_str::<serde_json::Value>(previous).is_err() {
            // Not plain JSON (comments, a half-finished edit): it cannot be
            // merged, so keep the user's copy beside the replacement.
            let backup = dir.join("opencode.json.bak");
            std::fs::write(&backup, previous)
                .with_context(|| format!("failed to write {}", backup.display()))?;
            eprintln!(
                "agent: {} was not plain JSON; it is kept as {}",
                path.display(),
                backup.display()
            );
        }
    }
    std::fs::write(&path, text).with_context(|| format!("failed to write {}", path.display()))?;
    Ok(())
}

/// `ours` laid over the configuration already on disk: the `sinorag` MCP
/// server is replaced, everything else the file holds is kept.
fn merge_opencode_config(existing: Option<&str>, ours: serde_json::Value) -> serde_json::Value {
    let Some(serde_json::Value::Object(mut root)) =
        existing.and_then(|text| serde_json::from_str(text).ok())
    else {
        return ours;
    };
    root.entry("$schema")
        .or_insert_with(|| ours["$schema"].clone());
    let mcp = root
        .entry("mcp")
        .or_insert_with(|| serde_json::Value::Object(Default::default()));
    match mcp {
        serde_json::Value::Object(servers) => {
            servers.insert("sinorag".to_string(), ours["mcp"]["sinorag"].clone());
        }
        other => *other = ours["mcp"].clone(),
    }
    serde_json::Value::Object(root)
}

/// Refresh the sinorag-managed slice of `AGENTS.md` without clobbering any
/// user-authored content surrounding it. The managed slice is delimited by
/// HTML-comment sentinels; on each launch we replace what's between them.
fn write_agents_md(workdir: &std::path::Path) -> Result<()> {
    let path = workdir.join("AGENTS.md");
    let existing = std::fs::read_to_string(&path).unwrap_or_default();
    // A collection of the user's own documents (document intake) gets the
    // documents doctrine; a data root with CBETA in it keeps the research
    // doctrine, with a section on word-aware search when it also holds
    // English text. The MCP server makes the same choice for its
    // instructions.
    let parquet = workdir.join("data").join("passages.parquet");
    let body = crate::mcp::server::doctrine_for(&parquet, AGENTS_MD_MANAGED_BODY);
    let new_contents = update_managed_block_with(&existing, &body);
    if new_contents == existing {
        return Ok(());
    }
    std::fs::write(&path, new_contents)
        .with_context(|| format!("failed to write {}", path.display()))?;
    Ok(())
}

#[cfg(test)]
fn update_managed_block(existing: &str) -> String {
    update_managed_block_with(existing, AGENTS_MD_MANAGED_BODY)
}

fn update_managed_block_with(existing: &str, body: &str) -> String {
    let managed = format!(
        "{}\n{}\n{}",
        SENTINEL_BEGIN,
        body.trim_end(),
        SENTINEL_END,
    );

    match (existing.find(SENTINEL_BEGIN), existing.find(SENTINEL_END)) {
        (Some(start), Some(end)) if end > start => {
            // Replace the existing managed slice (and the line break right
            // after the END sentinel, if any) with the regenerated block.
            let end_of_sentinel = end + SENTINEL_END.len();
            let mut out = String::with_capacity(existing.len() + managed.len());
            out.push_str(&existing[..start]);
            out.push_str(&managed);
            out.push_str(&existing[end_of_sentinel..]);
            out
        }
        _ if existing.trim().is_empty() => format!("{managed}\n"),
        _ => {
            // User has their own AGENTS.md but no sentinels — prepend the
            // managed block so opencode sees it first; user content stays
            // intact below.
            format!("{managed}\n\n{existing}")
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn opencode_config_keeps_what_the_user_added() {
        let ours = json!({
            "$schema": "https://opencode.ai/config.json",
            "mcp": { "sinorag": { "type": "local", "command": ["new.exe", "mcp"], "enabled": true } }
        });
        let existing = r#"{
            "model": "anthropic/claude-sonnet-4-5",
            "mcp": {
                "sinorag": { "type": "local", "command": ["old.exe", "mcp"], "enabled": true },
                "other": { "type": "local", "command": ["other"] }
            }
        }"#;
        let merged = merge_opencode_config(Some(existing), ours.clone());
        assert_eq!(merged["model"], "anthropic/claude-sonnet-4-5");
        assert_eq!(merged["mcp"]["other"]["command"][0], "other");
        assert_eq!(merged["mcp"]["sinorag"]["command"][0], "new.exe");
        assert_eq!(merged["$schema"], "https://opencode.ai/config.json");

        // Nothing there, or nothing usable: ours as it is.
        assert_eq!(merge_opencode_config(None, ours.clone()), ours);
        assert_eq!(merge_opencode_config(Some("// notes\n{"), ours.clone()), ours);
    }

    #[test]
    fn writes_block_into_empty_file() {
        let out = update_managed_block("");
        assert!(out.contains(SENTINEL_BEGIN));
        assert!(out.contains(SENTINEL_END));
    }

    #[test]
    fn prepends_block_when_user_content_has_no_sentinels() {
        let out = update_managed_block("# My notes\n\nhello\n");
        assert!(out.starts_with(SENTINEL_BEGIN));
        assert!(out.contains("# My notes"));
    }

    #[test]
    fn replaces_only_the_managed_slice() {
        let prior =
            format!("# Above\n\n{SENTINEL_BEGIN}\nold managed body\n{SENTINEL_END}\n\n# Below\n");
        let out = update_managed_block(&prior);
        assert!(out.contains("# Above"));
        assert!(out.contains("# Below"));
        assert!(!out.contains("old managed body"));
        assert!(out.contains("SinoRAG Research Agent"));
    }
}
